// no-moonbeam-on-base (owner 2026-11-22, first said 2026-10-26): Moonbeam is the venue and the policy; the chain is a
// settlement detail, not its name. So "Moonbeam on Base", "Moonbeam's hook on Base" and "built on Base" never reach a
// tracked source file or a served JSON. The same pattern is the scanner's category `floskeln` (~/bin/slop-scan).
// Where the chain is a needed fact, write "(Base)" or "chain 8453" in its own place, never glued to the name.
import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const MOONBEAM_ON_BASE = /\bbuilt on Base\b|\bMoonbeam(?:['’]s)?(?: [A-Za-z0-9-]+){0,2} on Base\b/i;

const CODE = /\.(ts|tsx|js|jsx|mjs|cjs|json)$/;
const SKIP_PATH = /(^|\/)(node_modules|dist|build|vendor|fixtures?|golden|snapshots?|__snapshots__|generated|gen)(\/|$)|\.generated\.|\.min\.|\.d\.ts$|-lock\.|\.lock$|\.snap$|\.map$|\.test\.|\.spec\.|_test\.|(^|\/)tests?\//;
const GENERATED_HEAD = /\b(generated by|do not edit)\b/i;

// tracked source files (src/, scripts/, packages/, bin/) and the JSON the package ships (src/); tests, fixtures and generated files are out
function guardedFiles(): string[] {
  const all = execFileSync('git', ['ls-files'], { encoding: 'utf8' }).split('\n').filter(Boolean);
  return all
    .filter((f) => CODE.test(f) && (f.endsWith('.json') ? /^src\//.test(f) : /^(src|scripts|packages|bin)\//.test(f)))
    .filter((f) => !SKIP_PATH.test(f))
    .filter((f) => !GENERATED_HEAD.test(readFileSync(f, 'utf8').slice(0, 400)));
}

describe('no-moonbeam-on-base: just "Moonbeam", never "Moonbeam on Base" or "built on Base"', () => {
  it('the pattern catches the policy wording and lets the chain stand alone as a fact', () => {
    for (const s of ['Moonbeam on Base', 'Moonbeam’s hook on Base', 'Moonbeam ACP on Base', 'Moonbeam’s V2 factory on Base', 'built on Base']) {
      expect(MOONBEAM_ON_BASE.test(s), s).toBe(true);
    }
    for (const s of ['Moonbeam ACP (Base)', 'Moonbeam contracts sit on chain 8453 (Base)', 'Virtuals ACP jobs on Base']) {
      expect(MOONBEAM_ON_BASE.test(s), s).toBe(false);
    }
  });

  it('no tracked non-test source file or served JSON carries the phrase', () => {
    const hits: string[] = [];
    for (const f of guardedFiles()) {
      readFileSync(f, 'utf8').split('\n').forEach((line, i) => {
        if (MOONBEAM_ON_BASE.test(line)) hits.push(`${f}:${i + 1}`);
      });
    }
    expect(hits).toEqual([]);
  });
});
