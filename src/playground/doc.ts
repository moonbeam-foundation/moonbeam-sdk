/**
 * docs/playground.md, generated from the table and the cases: who signs each role per network, each case's steps and status,
 * and the gaps. `node scripts/gen-playground.mjs` writes it; test/playground.test.ts fails when the file drifts from this.
 */
import { CASE_IDS, CASES, stepsOf } from './cases.js';
import type { StepTemplate, Via } from './cases.js';
import { gapsOf, NET_IDS, NETS, SIGNER_ROLES, statusOn } from './nets.js';

const s = (v: number | null): string => (v === null ? 'read from the hook' : `${v} s`);
const steps = (t: readonly StepTemplate[]): string =>
  t.map((x, i) => `${i + 1}. ${x.stage} · \`${x.fn}\` · ${x.role}${x.waits ? ` (after the ${x.waits === 'deadline' ? 'deadline' : `${x.waits} window`})` : ''}`).join('\n');

export function playgroundDoc(): string {
  const L: string[] = [];
  const nets = NET_IDS.map((id) => NETS[id]);
  L.push('# The playground: devnet and Base', '',
    '<!-- GENERATED by scripts/gen-playground.mjs from src/playground (NETS and CASES). Do not edit. -->', '',
    '`@moonbeam-foundation/sdk/playground` is one switch between the Moonbeam devnet and Base. Every cover case of a covered job is one',
    'plan with the same steps on both networks; only the signers, the chain id and the addresses differ. Base refuses until its',
    'gates are met: `allowMainnet: true`, a per-run budget above 0, and two green devnet runs of the market.', '',
    'A `wallet:` signer is a user wallet (on the devnet, a test wallet made for one run). A `coord:` signer is a sign request on the',
    'coord pipe for that purpose: Moonbeam signs it there, and the SDK never holds a key. A role with no signer is a gap: every case',
    'that needs it is refused on that network. The addresses are never in the table: they come in the placement the caller passes.', '');

  L.push('## The networks', '', `| | ${nets.map((n) => `${n.id}`).join(' | ')} |`, `|---|${nets.map(() => '---').join('|')}|`,
    `| chain id | ${nets.map((n) => n.chainId).join(' | ')} |`,
    `| token | ${nets.map((n) => `${n.token.symbol} (${n.token.decimals} decimals)`).join(' | ')} |`,
    `| review window | ${nets.map((n) => s(n.windows.reviewS)).join(' | ')} |`,
    `| dispute window | ${nets.map((n) => s(n.windows.disputeS)).join(' | ')} |`,
    `| arbitration window | ${nets.map((n) => s(n.windows.arbitrationS)).join(' | ')} |`, '');

  L.push('## Who signs each role', '', `| role | ${nets.map((n) => n.id).join(' | ')} |`, `|---|${nets.map(() => '---').join('|')}|`);
  for (const r of SIGNER_ROLES) L.push(`| ${r} | ${nets.map((n) => (n.signers[r] === null ? '**none yet** (gap)' : `\`${n.signers[r]}\``)).join(' | ')} |`);
  L.push('');

  L.push('## The cases', '', `| case | ending | ${nets.map((n) => n.id).join(' | ')} |`, `|---|---|${nets.map(() => '---').join('|')}|`);
  for (const id of CASE_IDS) {
    const c = CASES[id];
    L.push(`| \`${id}\` | ${c.ending ?? '—'} | ${nets.map((n) => statusOn(n, id)).join(' | ')} |`);
  }
  L.push('');
  for (const id of CASE_IDS) {
    const c = CASES[id];
    L.push(`### \`${id}\``, '', `${c.title}.`, '');
    if (c.status === 'not_built') { L.push(`Not built: ${c.reason}. No plan is made for it on either network.`, ''); continue; }
    if (c.vias) {
      for (const via of c.vias as readonly Via[])
        L.push(`With \`via: '${via}'\` (${nets.map((n) => `${n.id}: ${statusOn(n, id, via)}`).join(', ')}):`, '', steps(stepsOf(id, via)), '');
    } else L.push(steps(stepsOf(id)), '');
    L.push(`Lights: ${c.lights.length ? c.lights.join(' · ') : 'none (no sale)'}.`, '');
  }

  L.push('## The gaps', '');
  for (const n of nets) {
    const g = gapsOf(n);
    if (!g.length) { L.push(`- **${n.id}**: none.`); continue; }
    for (const x of g) L.push(`- **${n.id}**, ${x.role}: no coord sign purpose yet. Refused: ${x.blocks.length ? x.blocks.map((b) => `\`${b.case}\`${b.via ? ` (${b.via})` : ''}`).join(', ') : 'no built case'}.`);
  }
  L.push('', '## The lights', '',
    'Each light of a sale turns on only from an ack on the coord pipe plus an event on chain:', '',
    '- listed: `GET /v1/listed` (the sale run’s listed ack) and the hook’s `JobOpened` naming the seller;',
    '- bought: the fund call’s ack and `EconomyCommitted`;',
    '- delivered: the delivery’s ack and `Submitted`;',
    '- settled: the sale run’s settled stage and the hook’s `Settled`;',
    '- paid: the payout ack and the chain transfer of the seller’s leg to the seller.', '');
  return L.join('\n');
}
