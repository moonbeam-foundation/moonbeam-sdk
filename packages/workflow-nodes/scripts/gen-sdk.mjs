// Writes nodes/Moonbeam/sdk.generated.ts from @moonbeam-foundation/sdk: the venue ids and names, the five lights of a
// journey, the markets of the list step and the SDK version they were read from. The node ships with no run-time
// dependency (a workflow node package may not have one), so what it takes from the SDK is copied here at build time and
// held equal by `npm run gen:check` and the parity tests (test/sdk-parity.test.js).
//
//   node scripts/gen-sdk.mjs           write the file
//   node scripts/gen-sdk.mjs --check   fail when the file differs from what the SDK says now
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'nodes/Moonbeam/sdk.generated.ts');
const require = createRequire(import.meta.url);
const sdkPkg = require('@moonbeam-foundation/sdk/package.json');
const m = await import('@moonbeam-foundation/sdk/market');

const [major, minor] = sdkPkg.version.split('.').map(Number);
if (major !== 0 || minor < 13) throw new Error(`the node needs @moonbeam-foundation/sdk ^0.13.0 (journey); found ${sdkPkg.version}`);

const venues = m.VENUE_IDS.map((id) => ({ id, name: m.venueById(id).name }));
const q = (v) => JSON.stringify(v);
const listNames = Object.fromEntries(Object.entries(m.LIST_MARKET_OF).filter(([, mk]) => m.LIST_MARKETS.includes(mk)).map(([v, mk]) => [mk, m.venueById(v).name]));
const text = `// Generated by scripts/gen-sdk.mjs from @moonbeam-foundation/sdk ${sdkPkg.version}. Do not edit: run npm run gen.

/** The SDK version these constants were read from. */
export const SDK_VERSION = ${q(sdkPkg.version)};

/** Every venue a journey answers for, in the SDK's order (VENUE_IDS), with its name (VENUES[].name). */
export const VENUES: ReadonlyArray<{ id: string; name: string }> = ${q(venues)};

/** The five lights of an agent on a venue (JOURNEY_LEDS). */
export const JOURNEY_LEDS: readonly string[] = ${q([...m.JOURNEY_LEDS])};

/** The schema a journey answers (JOURNEY_SCHEMA). */
export const JOURNEY_SCHEMA = ${q(m.JOURNEY_SCHEMA)};

/** The markets the list step lists on (LIST_MARKETS). */
export const LIST_MARKETS: readonly string[] = ${q([...m.LIST_MARKETS])};

/** Each list market's name, its venue's (LIST_MARKET_OF, VENUES[].name). */
export const LIST_MARKET_NAMES: Readonly<Record<string, string>> = ${q(listNames)};
`;

if (process.argv.includes('--check')) {
	let now = '';
	try { now = readFileSync(out, 'utf8'); } catch { /* missing */ }
	if (now !== text) { console.error(`${path.relative(root, out)} differs from @moonbeam-foundation/sdk ${sdkPkg.version}: run npm run gen`); process.exit(1); }
	console.log(`${path.relative(root, out)} matches @moonbeam-foundation/sdk ${sdkPkg.version}`);
} else {
	writeFileSync(out, text);
	console.log(`wrote ${path.relative(root, out)} from @moonbeam-foundation/sdk ${sdkPkg.version}`);
}
