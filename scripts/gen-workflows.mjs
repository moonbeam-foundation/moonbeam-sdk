#!/usr/bin/env node
// The Studio's workflows (src/workflows/studio-workflows.json, exported from the Moonbeam Studio's own templates) as a typed
// module: src/workflows/data.ts. `--check` fails when the module is not the JSON's.
import { readFileSync, writeFileSync } from 'node:fs';
const src = new URL('../src/workflows/studio-workflows.json', import.meta.url);
const out = new URL('../src/workflows/data.ts', import.meta.url);
const data = JSON.parse(readFileSync(src, 'utf8'));
const text = `// GENERATED by scripts/gen-workflows.mjs from studio-workflows.json (the Moonbeam Studio's workflow templates). Do not edit.\n` +
  `import type { Workflow } from './types.js';\n\nexport const WORKFLOW_DATA: readonly Workflow[] = ${JSON.stringify(data, null, 1)};\n`;
if (process.argv.includes('--check')) {
  let now = ''; try { now = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (now !== text) { console.error('src/workflows/data.ts is not studio-workflows.json: run node scripts/gen-workflows.mjs'); process.exit(1); }
  console.log(`workflows: ${data.length} in step with studio-workflows.json`);
} else { writeFileSync(out, text); console.log(`wrote src/workflows/data.ts (${data.length} workflows)`); }
