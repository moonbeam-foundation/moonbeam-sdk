// _VENUE_PATHS_v1_: Moonbeam's part of coord's venue paths (coord lang/gen/venue-paths.public.json, consumers.json row `venue-paths`).
// Every kept market × list · buy · sell, each step with its read and its stream row, the rungs a run proved, and the SDK run
// file of each feature a run covers. Pure: scripts/gen-paths.mjs does the reading and writing, test/io/runs.test.ts the checking.
// Nothing here is typed by hand: the markets are coord's own `kept.moonbeam`, in coord's `order`.

export const RULE = '_VENUE_PATHS_v1_';
export const PUBLIC_FILE = 'lang/gen/venue-paths.public.json';
/** where coord's run of a feature is kept in this SDK: test/io/fixtures/<market>/<stage>/run-<rung>-<op>.json */
export const runPath = (market, stage, rung, op) => `test/io/fixtures/${market}/${stage}/run-${rung}-${op}.json`;
/** a run file, as opposed to a recorded coord call (test/io/coverage.json counts only those) */
export const isRunFile = (name) => /^run-[a-z]+-[a-z]+\.json$/.test(name);

/** a recorded read of one step of a rung (scripts/record-api-rung.mjs): read-<route>.<rung>-<op>-<step>.json, not a cell of the coverage matrix */
export const isRungFile = (name) => /\.(api|live)-[a-z]+-[a-z_]+\.json$/.test(name);

/** a row as the SDK keeps it: how a step is signed stays with the operator, and a mainnet run carries Moonbeam's own ids only */
const publicRow = (r) => ({ ...r,
  steps: (r.steps ?? []).map((s) => {
    const out = { ...s };
    if (s?.stream && typeof s.stream === 'object') { const { signer: _signer, ...stream } = s.stream; out.stream = stream; }
    if (s?.sign && typeof s.sign === 'object') { const { key: _key, ...sign } = s.sign; out.sign = sign; }
    return out;
  }),
  features: (r.features ?? []).map((f) => (f?.live ? { ...f, live: { ...f.live, ids: f.live.ids?.moonbeam ?? {}, needs: f.live.needs?.moonbeam ?? [] } } : f)),
});

/** Moonbeam's part of the public paths: its kept markets in coord's order, their rows and gaps, the coord sha they came from. */
export function moonbeamPaths(pub, sha, known = null) {
  if (pub?.rule !== 'VENUE_PATHS_v1' || !Array.isArray(pub.rows)) throw new Error('not coord venue paths (rule VENUE_PATHS_v1, rows)');
  if (!/^[0-9a-f]{40}$/.test(sha ?? '')) throw new Error(`no coord sha (${sha})`);
  const kept = pub.kept?.moonbeam;
  if (!Array.isArray(kept) || !kept.length) throw new Error('coord venue paths name no Moonbeam markets (kept.moonbeam)');
  // a market the SDK names differently (known lacks coord's id) has its own table row and is not in these public paths
  const markets = [...pub.order.filter((m) => kept.includes(m)), ...kept.filter((m) => !pub.order.includes(m))].filter((m) => !known || known.has(m));
  const rows = pub.rows.filter((r) => markets.includes(r.market) && (r.cohorts ?? []).includes('moonbeam'))
    .sort((a, b) => markets.indexOf(a.market) - markets.indexOf(b.market)).map(publicRow);
  const gaps = (pub.gaps ?? []).filter((g) => markets.includes(g.market));
  return { schema: 'moonbeam.venue-paths.v1', rule: `${RULE}: Moonbeam's kept markets of coord's venue paths; generated by scripts/gen-paths.mjs: do not edit`,
    coord: { sha, file: PUBLIC_FILE }, markets, rows, gaps };
}

export const LIVE_RULE = '_MAINNET_IO_v1_';
/** One run file per fixture a feature names: the run, the features and stage it covers, and the steps of its path. A feature may name
 *  two: the run coord itself made (fork or devnet), and the mainnet run an outside party proved (`live`, _MAINNET_IO_v1_). */
export function runFiles(paths) {
  const out = new Map();
  const put = (r, f, x, extra, rule) => {
    if (!x.run?.rung || !x.run?.ref || !x.run?.on) throw new Error(`${r.market}.${r.op}.${f.feature} names ${x.fixture} without its run`);
    const want = runPath(r.market, f.stage, x.run.rung, r.op);
    if (x.fixture !== want) throw new Error(`${r.market}.${r.op}.${f.feature}: coord names ${x.fixture}, the SDK keeps this run at ${want}`);
    const prev = out.get(x.fixture);
    if (prev) { if (prev.run.ref !== x.run.ref) throw new Error(`${x.fixture}: two runs (${prev.run.ref}, ${x.run.ref})`); prev.features.push(f.feature); return; }
    out.set(x.fixture, {
      schema: 'moonbeam.io.run.v1', rule,
      market: r.market, op: r.op, stage: f.stage, features: [f.feature], run: x.run, ...extra,
      steps: (r.steps ?? []).map((s) => ({ id: s.id, leaves: s.leaves, read: s.read ?? null, party: s.party ?? null })),
      coord_sha: paths.coord.sha,
    });
  };
  for (const r of paths.rows) for (const f of r.features ?? []) {
    if (f.fixture) put(r, f, f, {}, `${RULE}: a run coord proved for this market's path, kept as the SDK's own evidence of the step; generated by scripts/gen-paths.mjs: do not edit`);
    if (f.live) {
      if (f.live.run?.rung !== 'live') throw new Error(`${r.market}.${r.op}.${f.feature}: its mainnet run is on rung ${f.live.run?.rung}, not live`);
      const ids = (r.steps ?? []).map((s) => s.id);
      for (const id of f.live.steps ?? []) if (!ids.includes(id)) throw new Error(`${r.market}.${r.op}.${f.feature}: its mainnet run covers ${id}, which is no step of the path`);
      put(r, f, f.live, { covers: [...(f.live.steps ?? [])], ids: { ...(f.live.ids ?? {}) }, needs: [...(f.live.needs ?? [])] },
        `${LIVE_RULE}: a mainnet run of this market's path that an outside party proved; with the recorded read of each step it covers, it is what a live cell stands on; generated by scripts/gen-paths.mjs: do not edit`);
    }
  }
  return out;
}

/**
 * _MAINNET_IO_v1_: per market and feature, the mainnet run and the recorded read of each step it covers. `recorded` is every rung
 * fixture on disk by path (isRungFile). A step is kept only by a read of this very run that answered 200 (a priced door: its 402 with terms); `proven` needs every one.
 */
export function mainnetProofs(paths, recorded) {
  const out = {};
  // a step is proven by a read that answered 200, or by a priced door's own 402 with its terms (recorded as a wall)
  const reads = [...recorded].filter(([, fx]) => fx?.rung === 'live' && (fx?.response?.status === 200 || (fx?.wall === true && fx?.response?.status === 402)));
  for (const r of paths.rows) for (const f of r.features ?? []) {
    if (!f.live) continue;
    const steps = Object.fromEntries(f.live.steps.map((id) => [id, reads.find(([, fx]) => fx.market === r.market && fx.run === f.live.run.ref && fx.path?.op === r.op && fx.path?.step === id)?.[0] ?? null]));
    (out[r.market] ??= {})[f.feature] = { op: r.op, ref: f.live.run.ref, on: f.live.run.on, run: f.live.fixture, steps, proven: f.live.steps.length > 0 && Object.values(steps).every(Boolean) };
  }
  return out;
}

/** src/market/venue-mainnet-data.ts from mainnetProofs() */
export const renderMainnet = (proofs) => `// GENERATED by scripts/gen-paths.mjs from venue-paths.json and the mainnet reads recorded under test/io/fixtures (${LIVE_RULE}). Do not edit.\n` +
  `import type { MainnetProofs } from './cohorts.js';\n\nexport const VENUE_MAINNET: MainnetProofs = ${JSON.stringify(proofs, null, 1)};\n`;

const RUNG = { fork: 'fork', devnet: 'devnet', api: 'api', live: 'mainnet' };
const proved = (r) => Object.keys(RUNG).filter((k) => { const v = r.rungs?.[k]; return v && (k === 'live' ? v.proof === 'proven' : v.ok !== false); }).map((k) => RUNG[k]);
const txs = (r) => { const m = r.tx?.mainnet?.count ?? 0, d = Object.keys(r.tx?.devnet ?? {}).length; return [m ? `${m} on Base` : null, d ? `${d} on devnet` : null].filter(Boolean).join(', ') || '—'; };
const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|');

/** docs/PATHS.md: per market, its paths, the steps of each, what a run proved, the run files and the gaps. */
export function renderPaths(paths, nameOf = (id) => id, proofs = {}) {
  const L = [
    '# Venue paths',
    '',
    `<!-- ${RULE}: generated by scripts/gen-paths.mjs from coord ${paths.coord.sha.slice(0, 9)} (${paths.coord.file}): do not edit -->`,
    '',
    'Each market Moonbeam lists on, with its three paths: list, buy and sell. Every step names what it leaves behind and the read that shows it.',
    '',
    'A run is kept in `test/io/fixtures`. A step reads **live** in `VENUES` only on a mainnet run (`run-live-<path>.json`) whose every covered step has its recorded read beside it.',
    '',
    'A fork or devnet run is Moonbeam\'s own evidence of the code, and never a public word.',
    '',
  ];
  for (const m of paths.markets) {
    L.push(`## ${nameOf(m)}`, '');
    L.push('| Path | What it does | Steps | Proved by | Transactions | Run file | Mainnet reads kept |', '|---|---|---|---|---|---|---|');
    for (const r of paths.rows.filter((x) => x.market === m)) {
      const files = [...new Set((r.features ?? []).flatMap((f) => [f.fixture, f.live?.fixture]).filter(Boolean))].map((f) => `\`${f.replace(/^test\/io\/fixtures\//, '')}\``).join('<br>') || '—';
      const kept = (r.features ?? []).filter((f) => f.live).map((f) => { const p = proofs[r.market]?.[f.feature]; const n = Object.values(p?.steps ?? {}).filter(Boolean).length; return `${f.feature}: ${n} of ${f.live.steps.length} reads`; }).join('<br>') || '—';
      L.push(`| ${r.op} | ${cell(r.what)} | ${(r.steps ?? []).map((s) => s.id).join(' → ') || '—'} | ${proved(r).join(', ') || 'not yet'} | ${txs(r)} | ${files} | ${kept} |`);
    }
    const g = paths.gaps.filter((x) => x.market === m);
    if (g.length) { L.push('', 'Not yet:', ''); for (const x of g) L.push(`- ${x.op} · ${x.step}: ${x.why}`); }
    L.push('');
  }
  return `${L.join('\n').trimEnd()}\n`;
}
