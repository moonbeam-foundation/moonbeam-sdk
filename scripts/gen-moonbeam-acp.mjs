#!/usr/bin/env node
/**
 * Generate src/acp/moonbeam-acp.generated.ts from the coordination layer's address registry (addresses.json): the Moonbeam ACP
 * contracts on Base (system `moonbeam-acp`: the assurance hook and its implementation, the pool factory, every coverage pool),
 * the tokens the hook prices in (system `tokens`: GLMR, USDC on Base) and the judge's decision logs (system `jev`).
 *
 *   node scripts/gen-moonbeam-acp.mjs <path/to/addresses.json>
 *   ADDRESSES_JSON=<path/to/addresses.json> node scripts/gen-moonbeam-acp.mjs
 *   node scripts/gen-moonbeam-acp.mjs <path> --check   # exit 1 if the committed file is stale
 *
 * No dependencies. The generated file is committed; never hand-edit it. An address is never typed in this package: it is read
 * from the registry, with the status the registry gives it (live · scheduled-change · superseded · devnet-only). Test-network
 * rows are never emitted: a test network's addresses are read at runtime (./devnet).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
const src = args.find((a) => !a.startsWith('--')) ?? process.env.ADDRESSES_JSON;
if (!src) {
  console.error('usage: gen-moonbeam-acp.mjs <addresses.json> [--check]  (or set ADDRESSES_JSON)');
  process.exit(2);
}
const reg = JSON.parse(readFileSync(src, 'utf8'));
const rows = (system) => (reg.systems?.[system]?.contracts ?? []);
const one = (system, chain, re) => {
  const hit = rows(system).find((c) => Number(c.chain) === chain && re.test(String(c.name)));
  if (!hit) throw new Error(`${system} on ${chain}: no row matches ${re}`);
  return hit;
};
const BASE = 8453;
const hook = one('moonbeam-acp', BASE, /^AssuranceHook \(proxy\)$/);
const hookImpl = one('moonbeam-acp', BASE, /^AssuranceHook V\d+ \(implementation\)$/);
const factory = one('moonbeam-acp', BASE, /^PoolFactory \(proxy\)$/);
const pools = rows('moonbeam-acp').filter((c) => Number(c.chain) === BASE && /^CoveragePool #\d+$/.test(String(c.name)) && c.status === 'live')
  .sort((a, b) => Number(a.name.replace(/\D/g, '')) - Number(b.name.replace(/\D/g, '')));
const glmr = one('tokens', BASE, /^GLMR$/);
const usdc = one('tokens', BASE, /^USDC$/);
const log = one('jev', BASE, /^JevDecisionLog$/);
const answerLog = one('jev', BASE, /^JevAnswerLog$/);
const answerLogV2 = one('jev', BASE, /^JevAnswerLogV2$/);
const adapterV5 = one('jev', BASE, /^JudgeAdapterV5$/);
const v5 = one('v5-verifier', BASE, /^TaifoonV5ProofVerifier \(gated\)$/);
const since = rows('moonbeam-acp').map((c) => c.deploy?.at ?? c.deployed_at ?? c.since ?? null).filter((x) => typeof x === 'string').sort()[0] ?? null;

const q = (s) => JSON.stringify(String(s));
const note = (c) => q(String(c.notes ?? '').replace(/\s+/g, ' ').slice(0, 220));
const body = `// GENERATED by scripts/gen-moonbeam-acp.mjs from the address registry (addresses.json; systems moonbeam-acp, tokens, jev, v5-verifier).
// Do not edit: run the script. Every address here is read from the registry, with the status the registry gives it.
import type { Address } from '../onboard/index.js';

export type RegistryStatus = 'live' | 'scheduled-change' | 'superseded' | 'devnet-only';
export interface RegistryContract { readonly name: string; readonly address: Address; readonly chainId: number; readonly status: RegistryStatus; readonly note: string }

/** The assurance hook Moonbeam runs on Base (an ERC-1967 proxy); its status is the registry's word on it. */
export const MOONBEAM_HOOK: RegistryContract = Object.freeze({ name: ${q(hook.name)}, address: ${q(hook.address)} as Address, chainId: ${BASE}, status: ${q(hook.status)} as RegistryStatus, note: ${note(hook)} });
/** The implementation behind the hook proxy today. */
export const MOONBEAM_HOOK_IMPLEMENTATION: RegistryContract = Object.freeze({ name: ${q(hookImpl.name)}, address: ${q(hookImpl.address)} as Address, chainId: ${BASE}, status: ${q(hookImpl.status)} as RegistryStatus, note: ${note(hookImpl)} });
/** The pool factory (an ERC-1967 proxy): createPool is permissionless, one pool per seller and asset. */
export const MOONBEAM_POOL_FACTORY: RegistryContract = Object.freeze({ name: ${q(factory.name)}, address: ${q(factory.address)} as Address, chainId: ${BASE}, status: ${q(factory.status)} as RegistryStatus, note: ${note(factory)} });
/** Every live coverage pool the registry lists, in creation order. */
export const MOONBEAM_COVERAGE_POOLS: readonly RegistryContract[] = Object.freeze([
${pools.map((p) => `  Object.freeze({ name: ${q(p.name)}, address: ${q(p.address)} as Address, chainId: ${BASE}, status: ${q(p.status)} as RegistryStatus, note: ${note(p)} }),`).join('\n')}
]);
/** GLMR on Base: the only asset the hook covers in (the USDC route closed on 2026-09-29; the registry's hook row says so). */
export const BASE_GLMR_TOKEN: RegistryContract & { readonly decimals: 18; readonly symbol: 'GLMR' } = Object.freeze({ name: 'GLMR', symbol: 'GLMR', decimals: 18, address: ${q(glmr.address)} as Address, chainId: ${BASE}, status: ${q(glmr.status)} as RegistryStatus, note: ${note(glmr)} });
/** USDC on Base, 6 decimals: an uncovered job's token. */
export const BASE_USDC_TOKEN: RegistryContract & { readonly decimals: 6; readonly symbol: 'USDC' } = Object.freeze({ name: 'USDC', symbol: 'USDC', decimals: 6, address: ${q(usdc.address)} as Address, chainId: ${BASE}, status: ${q(usdc.status)} as RegistryStatus, note: ${note(usdc)} });
/** The judge's decision log on Base: every decision is recorded here before it is used. */
export const JEV_DECISION_LOG: RegistryContract = Object.freeze({ name: ${q(log.name)}, address: ${q(log.address)} as Address, chainId: ${BASE}, status: ${q(log.status)} as RegistryStatus, note: ${note(log)} });
/** The judge's answer log on Base (jev.answer.v1 digests). */
export const JEV_ANSWER_LOG: RegistryContract = Object.freeze({ name: ${q(answerLog.name)}, address: ${q(answerLog.address)} as Address, chainId: ${BASE}, status: ${q(answerLog.status)} as RegistryStatus, note: ${note(answerLog)} });
/** The judge's second answer log on Base (the same JevAnswered event and recordedAt; a guardian rotates its recorder). A
 *  reader looks up an answers digest in both logs. */
export const JEV_ANSWER_LOG_V2: RegistryContract = Object.freeze({ name: ${q(answerLogV2.name)}, address: ${q(answerLogV2.address)} as Address, chainId: ${BASE}, status: ${q(answerLogV2.status)} as RegistryStatus, note: ${note(answerLogV2)} });
/** The evaluator adapter on Base that posts an anchored verdict to its hook after a vetoable delay. */
export const JUDGE_ADAPTER_V5: RegistryContract = Object.freeze({ name: ${q(adapterV5.name)}, address: ${q(adapterV5.address)} as Address, chainId: ${BASE}, status: ${q(adapterV5.status)} as RegistryStatus, note: ${note(adapterV5)} });
/** The V5 proof verifier on Base (verify(blob) answers whether a served proof blob verifies). */
export const V5_PROOF_VERIFIER: RegistryContract = Object.freeze({ name: 'V5 proof verifier', address: ${q(v5.address)} as Address, chainId: ${BASE}, status: ${q(v5.status)} as RegistryStatus, note: '' });
/** The addresses by role, for code that only needs the address. */
export const REGISTRY = Object.freeze({ hook: MOONBEAM_HOOK.address, poolFactory: MOONBEAM_POOL_FACTORY.address, glmr: BASE_GLMR_TOKEN.address, usdc: BASE_USDC_TOKEN.address, decisionLog: JEV_DECISION_LOG.address, answerLog: JEV_ANSWER_LOG.address, answerLogV2: JEV_ANSWER_LOG_V2.address, judgeAdapterV5: JUDGE_ADAPTER_V5.address, v5Verifier: V5_PROOF_VERIFIER.address });
/** The earliest deployment date the registry records for the system, when it records one. */
export const MOONBEAM_ACP_SINCE: string | null = ${since === null ? 'null' : q(since)};
/** How many coverage pools the registry lists as live. */
export const MOONBEAM_POOL_COUNT = ${pools.length} as const;
`;

const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'acp', 'moonbeam-acp.generated.ts');
const had = (() => { try { return readFileSync(out, 'utf8'); } catch { return null; } })();
if (check) {
  if (had !== body) { console.error(`${out} is stale: run node scripts/gen-moonbeam-acp.mjs ${src}`); process.exit(1); }
  console.log(`${out}: current (${pools.length} pools, hook ${hook.status})`);
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out}: hook ${hook.address} (${hook.status}), factory ${factory.address}, ${pools.length} pools, GLMR ${glmr.address}, decision log ${log.address}`);
}
